// Copies ../index.html (the web app) into gymHtml.js so the Expo app ships the same page.
const fs = require("fs");
const path = require("path");

const src = fs.readFileSync(path.join(__dirname, "..", "..", "index.html"), "utf8");
const doc = `<!doctype html><html lang="en"><head>${src.split("</style>")[0]}</style></head><body>${src.split("</style>").slice(1).join("</style>")}</body></html>`;
fs.writeFileSync(
  path.join(__dirname, "..", "gymHtml.js"),
  `// Generated by scripts/embed-html.js from ../index.html. Do not edit by hand.\nexport default ${JSON.stringify(doc)};\n`
);
console.log("Embedded index.html into gymHtml.js");
